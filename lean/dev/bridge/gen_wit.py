"""Generate orbit-cover witnesses for TrCheck.orbitOk: for each universe avoider t of B*, a base automorphism
(g, pi) and a case representative r with permT g t = r, where permT g t has bit i = bit g(i) of t.
Untrusted: TrCheck.autOk / orbitOk re-check everything natively. Output: Lean file WitData.lean."""
import sys, json, numpy as np
sys.path.insert(0, '.')
from tr_sym import gens, group, apply
out = ['/-! generated by gen_wit.py (untrusted data; re-checked by TrCheck.orbitOk) -/', 'namespace TrCheck']
for tag in ['33', '34', '24x']:
    a, c = int(tag[0]), int(tag[1])
    names, P, OS, G = gens(a, c); n = len(names); P = [int(x) for x in P]
    E = group(G, n)
    U = np.load(f'st_{tag}.npz'); tr = [int(x) for x in U['tr']]; T = {t: i for i, t in enumerate(tr)}
    pl = json.load(open(f'case_{tag}_plan.json')); Bs = pl['Bstar']; reps = [r for r, _ in pl['reps']]
    av = [i for i, t in enumerate(tr) if t & Bs == 0]
    assert av == pl['avoiders'], tag
    def permT(g, t): return sum(1 << i for i in range(n) if t >> g[i] & 1)
    wit = []
    for i in av:
        found = None
        for p in E:
            pi = []
            for q in range(4):
                img = apply(p, P[q]); m = [r for r in range(4) if P[r] == img]
                if len(m) != 1: break
                pi.append(m[0])
            if len(pi) != 4: continue
            for r in reps:
                if permT(list(p), tr[i]) == tr[r]:
                    found = (i, list(p), pi, r); break
            if found: break
        assert found, (tag, i)
        wit.append(found)
    nm = 'wit' + tag
    out.append(f'def Bs{tag} : Nat := {Bs}')
    out.append(f'def reps{tag} : List Nat := {reps}')
    out.append(f'def {nm} : List (Nat × List Nat × List Nat × Nat) := [')
    out.append(',\n'.join(f'  ({i}, {g}, {pi}, {r})' for i, g, pi, r in wit))
    out.append(']')
    print(tag, 'avoiders', len(av), 'group', len(E), 'reps', reps)
out.append('end TrCheck')
open('../../../e616lean/bridge/WitData.lean', 'w').write('\n'.join(out) + '\n')
