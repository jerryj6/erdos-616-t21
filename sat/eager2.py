"""Faster eager enumeration (v2) of violating subfamilies of size <= 4 for Erdos #616, tau>=5 target.
Complement formulation: pool of T subset [n], S = [n] \\ T is the core part of an edge with r-|S| privates.
Violating = union of T's is [n] (S's have empty intersection) and span = |U S| + sum(r-|S|) <= 3r-3.
Enumeration: every covering family {T1..Tm} (m<=4) is generated by repeatedly choosing a pool set containing
the lowest still-uncovered point (any covering family can be ordered this way, so none is missed);
pruning: span of partial family > 3r-3 (span is monotone under adding sets).
Only families none of whose proper subfamilies cover [n] are emitted (others are implied).
Outputs canonical sorted index tuples (deduplicated)."""
import sys, itertools, time
import numpy as np
from numba import njit

@njit(cache=True)
def popc(x):
    c = 0
    while x:
        x &= x - 1
        c += 1
    return c

@njit(cache=True)
def lowbit(x):
    b = 0
    while not (x >> b) & 1:
        b += 1
    return b

@njit(cache=True)
def covers_sub(T, fam, m, X):
    # does a proper subfamily cover X?  (m<=4)
    for mask in range(1, (1 << m) - 1):
        u = 0
        for t in range(m):
            if (mask >> t) & 1:
                u |= T[fam[t]]
        if u == X:
            return True
    return False

@njit(cache=True)
def enum(T, n, r, sup_index, sup_ptr, out, maxm):
    X = (1 << n) - 1
    lim = 3 * r - 3
    cnt = 0
    fam = np.empty(4, np.int64)
    S = X ^ T
    w = np.empty(T.shape[0], np.int64)
    for i in range(T.shape[0]):
        w[i] = r - popc(S[i])
    # depth 1: sets containing point 0
    for p1 in range(sup_ptr[0], sup_ptr[1]):
        a = sup_index[p1]
        U1 = T[a]; SU1 = S[a]; W1 = w[a]
        R1 = X ^ U1
        b0 = lowbit(R1)
        for p2 in range(sup_ptr[b0], sup_ptr[b0 + 1]):
            b = sup_index[p2]
            U2 = U1 | T[b]; SU2 = SU1 | S[b]; W2 = W1 + w[b]
            if popc(SU2) + W2 > lim:
                continue
            if U2 == X:
                fam[0] = a; fam[1] = b
                if not covers_sub(T, fam, 2, X):
                    out[cnt, 0] = min(a, b); out[cnt, 1] = max(a, b); out[cnt, 2] = -1; out[cnt, 3] = -1
                    cnt += 1
                continue
            if maxm < 3:
                continue
            c0 = lowbit(X ^ U2)
            for p3 in range(sup_ptr[c0], sup_ptr[c0 + 1]):
                c = sup_index[p3]
                U3 = U2 | T[c]; SU3 = SU2 | S[c]; W3 = W2 + w[c]
                if popc(SU3) + W3 > lim:
                    continue
                if U3 == X:
                    fam[0] = a; fam[1] = b; fam[2] = c
                    if not covers_sub(T, fam, 3, X):
                        x = np.sort(fam[:3])
                        out[cnt, 0] = x[0]; out[cnt, 1] = x[1]; out[cnt, 2] = x[2]; out[cnt, 3] = -1
                        cnt += 1
                    continue
                if maxm < 4:
                    continue
                R3 = X ^ U3
                d0 = lowbit(R3)
                for p4 in range(sup_ptr[d0], sup_ptr[d0 + 1]):
                    d = sup_index[p4]
                    if (T[d] & R3) != R3:
                        continue
                    SU4 = SU3 | S[d]; W4 = W3 + w[d]
                    if popc(SU4) + W4 > lim:
                        continue
                    fam[0] = a; fam[1] = b; fam[2] = c; fam[3] = d
                    if covers_sub(T, fam, 4, X):
                        continue
                    x = np.sort(fam)
                    if x[0] == x[1] or x[1] == x[2] or x[2] == x[3]:
                        continue
                    out[cnt, 0] = x[0]; out[cnt, 1] = x[1]; out[cnt, 2] = x[2]; out[cnt, 3] = x[3]
                    cnt += 1
                    if cnt >= out.shape[0]:
                        return -1
    return cnt

def build(n, r, cmin, cmax, cap=60_000_000):
    Ts = [sum(1 << v for v in cc) for size in range(cmin, cmax + 1) for cc in itertools.combinations(range(n), size)]
    T = np.array(Ts, dtype=np.int64)
    lists = [np.nonzero((T >> v) & 1)[0] for v in range(n)]
    sup_ptr = np.zeros(n + 1, np.int64)
    for v in range(n):
        sup_ptr[v + 1] = sup_ptr[v] + len(lists[v])
    sup_index = np.concatenate(lists).astype(np.int64)
    out = np.zeros((cap, 4), np.int32)
    t0 = time.time()
    cnt = enum(T, n, r, sup_index, sup_ptr, out, 4)
    assert cnt >= 0, 'cap exceeded'
    fam = np.unique(out[:cnt], axis=0)
    del out
    k = (fam >= 0).sum(1)
    print(f'n={n} r={r} c={cmin}..{cmax} pool={len(T)}: raw {cnt} unique {len(fam)} by size',
          {int(s): int((k == s).sum()) for s in (2, 3, 4)}, f'({time.time()-t0:.1f}s)', flush=True)
    return T, fam

def write_cnf(path, n, T, fam, K=5):
    P1 = []
    for C in itertools.combinations(range(n), K - 1):
        cm = sum(1 << v for v in C)
        P1.append(np.nonzero((T & cm) == cm)[0] + 1)
    with open(path, 'w') as f:
        f.write(f'p cnf {len(T)} {len(P1) + len(fam)}\n')
        for lits in P1:
            f.write(' '.join(map(str, lits)) + ' 0\n')
        for row in fam:
            f.write(' '.join(str(-(int(x) + 1)) for x in row if x >= 0) + ' 0\n')

if __name__ == '__main__':
    n, r, cmin, cmax = map(int, sys.argv[1:5])
    T, fam = build(n, r, cmin, cmax)
    path = f'eager2_r{r}_k5_n{n}_c{cmin}-{cmax}.cnf'
    write_cnf(path, n, T, fam)
    np.save(path.replace('.cnf', '_pool.npy'), T)
    print('wrote', path, flush=True)
